    private void btnRegistrarProfesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarProfesorActionPerformed
        try {
            Profesor profesor = controlador.registrarProfesor(txtProfNombre.getText(), txtProfDireccion.getText(),
                    txtProfTelefono.getText(), txtProfFecha.getText(), txtProfCedula.getText(),
                    txtProfArea.getText(), txtProfValorHora.getText(), txtProfHoras.getText());
            JOptionPane.showMessageDialog(this, "Profesor " + profesor.getNombre() + " registrado.");
            limpiar(txtProfNombre, txtProfDireccion, txtProfTelefono, txtProfFecha, txtProfCedula,
                    txtProfArea, txtProfValorHora, txtProfHoras);
        } catch (IllegalArgumentException ex) {
            mostrarError(ex.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarProfesorActionPerformed

